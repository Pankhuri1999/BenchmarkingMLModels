def ms_per_sample(model, X, n=2000):
    Xs = X[: min(n, X.shape[0])]
    t0 = time.time()
    _ = model.predict(Xs)
    dt = time.time() - t0
    return float(1000.0 * dt / max(1, Xs.shape[0]))

